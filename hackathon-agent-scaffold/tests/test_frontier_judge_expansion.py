"""Pin the frontier Judge Mode expansion tour record
(eval-scorecard/FRONTIER_JUDGE_EXPANSION.md + frontier-judge-expansion.json,
generated by run_frontier_judge_expansion_eval.py).

Iteration 41: before this record, the console catalog exposed only
the original four issues, so no judge could run an expansion issue
through Judge Mode. The catalog now includes all nine expansion
issues (live-only), and this tour ran each of them LIVE over HTTP
under the all-frontier contest config at the 24-test baseline.
Measured outcome, pinned as recorded: 9/9 passed
(24 -> 28/28/27/29/27/28/27/27/27 in tour order, combined +32),
81 captions, every card muse-wonder-1.0 on every role. The prior
direct-pipeline summary embedded in the record must agree with the
iteration 35-37 batch records on disk.
"""
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RECORD = ROOT / "eval-scorecard" / "frontier-judge-expansion.json"
DOC = ROOT / "eval-scorecard" / "FRONTIER_JUDGE_EXPANSION.md"
sys.path.insert(0, str(Path(__file__).parent.parent))
import demo_ui  # noqa: E402
import run_frontier_judge_expansion_eval as runner  # noqa: E402

FRONTIER_MODELS = {
    "TRIAGE": ["muse-wonder-1.0"],
    "PLANNER": ["muse-wonder-1.0"],
    "CODER": ["muse-wonder-1.0"],
    "REVIEWER": ["muse-wonder-1.0"],
}
EXPECTED = (
    ("config_drift", 28, 4, 25121, 0.025412),
    ("health_check", 28, 4, 39475, 0.031852),
    ("alert_threshold", 27, 3, 15611, 0.017892),
    ("connection_pool", 29, 5, 19317, 0.034628),
    ("log_rotation", 27, 3, 41386, 0.044392),
    ("scheduled_job", 28, 4, 21226, 0.035984),
    ("retry_storm", 27, 3, 25994, 0.033416),
    ("deploy_token", 27, 3, 23452, 0.029892),
    ("api_pagination", 27, 3, 19929, 0.02522),
)


class TestFrontierJudgeExpansionRecord(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.record = json.loads(RECORD.read_text(encoding="utf-8"))
        cls.rows = {r["issue_id"]: r for r in cls.record["runs"]}

    def test_catalog_exposes_all_thirteen_issues(self):
        ids = [e["id"] for e in demo_ui.issue_catalog()]
        self.assertEqual(len(ids), 13)
        for issue_id in runner.TOUR_ORDER:
            self.assertIn(issue_id, ids)

    def test_all_nine_in_tour_order_live_frontier(self):
        self.assertEqual([r["issue_id"] for r in self.record["runs"]],
                         runner.TOUR_ORDER)
        self.assertEqual(self.record["model"], "muse-wonder-1.0")
        self.assertEqual(self.record["fallback_model"], "muse-spark-1.3")
        for row in self.record["runs"]:
            self.assertEqual(row["mode"], "live", row)
            self.assertTrue(row["judge_mode"], row)
            self.assertTrue(row["all_captions_judge_mode"], row)
            self.assertEqual(row["links_live_prs"], 3, row)
            self.assertEqual([s["stage"] for s in row["stages"]],
                             demo_ui.JUDGE_STAGES, row)

    def test_all_expansion_issues_passed_with_frontier_models(self):
        for issue_id, after, delta, elapsed, cost in EXPECTED:
            row = self.rows[issue_id]
            self.assertEqual(row["status"], "done", row)
            self.assertEqual(row["overall"], "pass", row)
            self.assertIsNone(row["error"], row)
            self.assertEqual(row["tests_before"], 24, row)
            self.assertEqual(row["tests_after"], after, row)
            self.assertEqual(row["tests_delta"], delta, row)
            self.assertEqual(row["captions"], 9, row)
            self.assertTrue(all(s["status"] == "pass"
                                for s in row["stages"]), row)
            self.assertEqual(row["total_elapsed_ms"], elapsed, row)
            self.assertEqual(row["cost_method"], "char_estimate", row)
            self.assertEqual(row["cost_calls"], 4, row)
            self.assertEqual(row["cost_total_usd_est"], cost, row)
            self.assertEqual(row["cost_per_role_models"],
                             FRONTIER_MODELS, row)

    def test_stage_timings_monotonic_where_recorded(self):
        for row in self.record["runs"]:
            elapsed = [s["elapsed_ms"] for s in row["stages"]
                       if s["elapsed_ms"] is not None]
            self.assertEqual(elapsed, sorted(elapsed), row)
            self.assertEqual(row["total_elapsed_ms"], elapsed[-1], row)

    def test_summary_recomputes_from_rows(self):
        self.assertEqual(runner.summarize(self.record["runs"]),
                         self.record["summary"])
        s = self.record["summary"]
        self.assertEqual(s["work_passed"], 9)
        self.assertEqual(s["work_total"], 9)
        self.assertEqual(s["total_tests_delta"], 32)
        self.assertEqual(s["total_captions"], 81)
        self.assertEqual(s["cost_total_usd_est"], 0.278688)
        self.assertEqual(s["total_elapsed_ms"], 231511)

    def test_prior_direct_pipeline_matches_batch_records(self):
        prior = self.record["prior_direct_pipeline"]
        self.assertEqual(prior, runner._prior_summary())
        self.assertEqual(prior["issues_passed"], "9/9")
        self.assertEqual(prior["test_growth"], 32)
        self.assertEqual(prior["total_usd_est"], 0.266644)
        self.assertEqual(prior["total_wall_clock_seconds"], 211.8)

    def test_config_label_names_connector_and_frontier(self):
        for token in ("custom.meta-model-api connector", "muse-wonder-1.0",
                      "muse-spark-1.3", "availability fallback",
                      "no env key"):
            self.assertIn(token, self.record["config"], token)

    def test_doc_is_runner_render_and_agrees(self):
        self.assertEqual(DOC.read_text(encoding="utf-8"),
                         runner.render_md(self.record))
        text = DOC.read_text(encoding="utf-8")
        for token in ("9/9", "+32", "config_drift", "deploy_token",
                      "api_pagination", "$0.2787", "231.51s",
                      "Oct 29, 2026", "opens no PR", "live-only"):
            self.assertIn(token, text, token)


if __name__ == "__main__":
    unittest.main()

"""Pin the claims-audit record (eval-scorecard/CLAIMS_AUDIT.md +
claims-audit.json, generated by run_claims_audit.py, maximizer
iteration 51).

The audit checks the judge-facing docs (SUBMISSION.md, README.md)
fresh against the measured records: demo suite really 24, the
full-bench summary recomputes from its rows, SUBMISSION.md carries
the recomputed figures with configuration-labeled costs, and the
split is framed as superseded for contest runs in both docs.
These tests recompute the bench figures and pin the doc's agreement.
"""
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RECORD = ROOT / "eval-scorecard" / "claims-audit.json"
DOC = ROOT / "eval-scorecard" / "CLAIMS_AUDIT.md"
sys.path.insert(0, str(Path(__file__).parent.parent))
import run_claims_audit as ca  # noqa: E402


class TestClaimsAuditRecord(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.record = json.loads(RECORD.read_text(encoding="utf-8"))
        cls.doc = DOC.read_text(encoding="utf-8")

    def test_all_checks_pass(self):
        self.assertTrue(self.record["all_checks_pass"])
        self.assertTrue(all(self.record["checks"].values()))
        self.assertEqual(set(self.record["checks"]), {
            "demo_suite_fresh_24", "full_bench_summary_recomputes",
            "submission_carries_full_bench_figures",
            "submission_labels_split_era_cost",
            "submission_split_framing_current",
            "readme_tooling_row_current", "readme_baseline_current"})

    def test_full_bench_recomputes_independently(self):
        bench = ca.full_bench_recompute()
        self.assertTrue(bench["matches"])
        self.assertEqual(bench["recomputed"]["work_issues_passed"], "12/12")
        self.assertEqual(bench["recomputed"]["test_growth"], 42)
        self.assertTrue(bench["recomputed"]["guardrail_escalated"])
        self.assertEqual(self.record["full_bench"]["recomputed"],
                         bench["recomputed"])

    def test_demo_suite_record(self):
        demo = self.record["demo_suite"]
        self.assertEqual((demo["tests"], demo["expected"], demo["ok"]),
                         (24, 24, True))

    def test_stale_framings_actually_fixed(self):
        readme = (ROOT / "README.md").read_text(encoding="utf-8")
        submission = (ROOT / "SUBMISSION.md").read_text(encoding="utf-8")
        self.assertNotIn(ca.STALE_README_TOKEN, readme)
        self.assertIn("24 passing", readme)
        self.assertIn("superseded for contest runs", readme)
        self.assertIn("split-config measurement", submission)
        self.assertNotIn("keeps the split:", submission)

    def test_doc_agrees_with_record(self):
        self.assertEqual(self.doc, ca.render_md(self.record))


if __name__ == "__main__":
    unittest.main()

"""Pin the live Judge Mode record (eval-scorecard/JUDGE_LIVE.md +
judge-live.json, generated by run_judge_live.py).

Judge Mode's tour was mock-only (test_judge_tour.py — plumbing proof).
This record is the self-guided path run LIVE: one click on
POST /api/judge/run with mode=live, the Tier 1 issue through the real
Meta Model API via the connector under the kept split. These tests
pin the measured snapshot: outcome, test delta, caption wiring,
per-stage timings, and the split models recorded in the closing
card's own per-role cost summary. Timings/cost are measured values
from that run; the deterministic structure is what must not drift.
"""
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RECORD = ROOT / "eval-scorecard" / "judge-live.json"
DOC = ROOT / "eval-scorecard" / "JUDGE_LIVE.md"
sys.path.insert(0, str(Path(__file__).parent.parent))
import demo_ui  # noqa: E402
import run_judge_live  # noqa: E402


class TestJudgeLiveRecord(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.record = json.loads(RECORD.read_text(encoding="utf-8"))
        cls.row = cls.record["runs"][0]

    def test_single_live_self_guided_run(self):
        self.assertEqual(len(self.record["runs"]), 1)
        self.assertEqual(self.row["issue_id"], "tier1")
        self.assertEqual(self.row["mode"], "live")
        self.assertTrue(self.row["judge_mode"])
        self.assertEqual(self.row["status"], "done")
        self.assertIsNone(self.row["error"])

    def test_run_passed_with_measured_delta(self):
        self.assertEqual(self.row["overall"], "pass")
        self.assertEqual(self.row["tests_before"], 6)
        self.assertEqual(self.row["tests_after"], 9)
        self.assertEqual(self.row["tests_delta"], 3)
        self.assertEqual([s["stage"] for s in self.row["stages"]],
                         demo_ui.JUDGE_STAGES)
        self.assertTrue(all(s["status"] == "pass"
                            for s in self.row["stages"]))

    def test_captions_and_stage_timings_recorded(self):
        self.assertEqual(self.row["captions"], 7)
        self.assertTrue(self.row["all_captions_judge_mode"])
        elapsed = [s["elapsed_ms"] for s in self.row["stages"]]
        self.assertTrue(all(isinstance(e, int) and e >= 0
                            for e in elapsed))
        self.assertEqual(elapsed, sorted(elapsed))
        self.assertEqual(self.row["total_elapsed_ms"], elapsed[-1])
        self.assertEqual(self.row["total_elapsed_ms"], 20437)

    def test_card_cost_records_the_split_models(self):
        self.assertEqual(self.row["cost_method"], "char_estimate")
        self.assertEqual(self.row["cost_calls"], 4)
        self.assertEqual(self.row["cost_total_usd_est"], 0.010789)
        self.assertEqual(self.row["cost_per_role_models"], {
            "TRIAGE": ["muse-spark-1.3"],
            "PLANNER": ["muse-spark-1.3"],
            "CODER": ["muse-wonder-1.0"],
            "REVIEWER": ["muse-wonder-1.0"],
        })
        self.assertEqual(self.row["links_live_prs"], 3)

    def test_summary_recomputes_from_row(self):
        self.assertEqual(run_judge_live.summarize(self.row),
                         self.record["summary"])
        self.assertTrue(self.record["summary"]["passed"])

    def test_config_label_names_connector_and_split(self):
        for token in ("custom.meta-model-api connector", "muse-wonder-1.0",
                      "muse-spark-1.3", "no env key"):
            self.assertIn(token, self.record["config"], token)

    def test_doc_agrees_with_record(self):
        text = DOC.read_text(encoding="utf-8")
        for token in ("live", "pass", "6 → 9", "+3", "20.44s", "$0.0108",
                      "not the demo video", "opens no PR"):
            self.assertIn(token, text, token)


if __name__ == "__main__":
    unittest.main()

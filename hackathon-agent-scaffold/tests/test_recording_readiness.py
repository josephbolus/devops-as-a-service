"""Pin the recording-readiness record (eval-scorecard/
RECORDING_READINESS.md + recording-readiness.json, generated by
run_recording_readiness.py, maximizer iteration 49).

The record verifies, fresh at generation time, every artifact the
Thu Oct 29 recording depends on: the four non-scaffold suites green,
a mock Judge Mode console smoke at the current 24-test baseline,
the fallback package at the current baseline, the run-of-show's
all-frontier pre-flight, and the submission checklist with only the
two human-owned items open. These tests recompute the summary from
the rows and pin the doc's agreement.
"""
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RECORD = ROOT / "eval-scorecard" / "recording-readiness.json"
DOC = ROOT / "eval-scorecard" / "RECORDING_READINESS.md"
sys.path.insert(0, str(Path(__file__).parent.parent))
import run_recording_readiness as rr  # noqa: E402


class TestRecordingReadinessRecord(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.record = json.loads(RECORD.read_text(encoding="utf-8"))
        cls.doc = DOC.read_text(encoding="utf-8")

    def test_all_checks_pass_and_recompute(self):
        rec = self.record
        self.assertTrue(rec["all_checks_pass"])
        self.assertTrue(all(rec["checks"].values()))
        self.assertEqual(rec["recording_date"], "2026-10-29")
        self.assertEqual(set(rec["checks"]), {
            "suites_ok", "smoke_tier1_pass", "smoke_guardrail_escalated",
            "fallbacks_current", "run_of_show_all_frontier",
            "submission_only_human_items_open", "current_docs_oct29"})

    def test_suites_match_static_counts(self):
        suites = {s["suite"]: s for s in self.record["suites"]}
        self.assertEqual(
            {k: (v["tests"], v["expected"], v["ok"]) for k, v in suites.items()},
            {name: (exp, exp, True) for name, _, exp in rr.SUITES})

    def test_console_smoke_rows(self):
        rows = {r["issue_id"]: r for r in self.record["console_smoke"]}
        t1 = rows["tier1"]
        self.assertEqual(t1["overall"], "pass")
        self.assertEqual((t1["tests_before"], t1["tests_after"],
                          t1["tests_delta"]), (24, 25, 1))
        self.assertTrue(t1["judge_mode"])
        self.assertEqual(t1["cost_total_usd_est"], 0.0)
        g = rows["guardrail"]
        self.assertEqual(g["overall"], "escalated")
        self.assertIsNone(g["tests_delta"])

    def test_fallback_rows_current_baseline(self):
        rows = {r["issue_id"]: r for r in self.record["fallbacks"]}
        for issue_id, (before, after) in rr.FALLBACK_DELTAS.items():
            row = rows[issue_id]
            self.assertTrue(row["passed"], row)
            self.assertEqual((row["tests_before"], row["tests_after"]),
                             (before, after), row)
            self.assertTrue(row["matches_current_baseline"], row)
        self.assertTrue(rows["guardrail"]["escalated"])
        self.assertFalse(rows["guardrail"]["passed"])

    def test_docs_block(self):
        docs = self.record["docs"]
        self.assertTrue(all(docs["run_of_show_all_frontier"].values()))
        self.assertEqual(set(docs["run_of_show_all_frontier"]),
                         set(rr.ROLES))
        self.assertEqual(len(docs["submission_unchecked_items"]), 2)
        self.assertTrue(docs["submission_video_placeholder_present"])
        self.assertTrue(docs["architecture_names_oct29"])
        self.assertTrue(docs["judge_mode_names_oct29"])

    def test_current_docs_actually_name_oct29(self):
        arch = (ROOT / "ARCHITECTURE.md").read_text(encoding="utf-8")
        judge = (ROOT / "JUDGE_MODE.md").read_text(encoding="utf-8")
        self.assertIn("Thu Oct 29, 2026", arch)
        self.assertIn("Oct 29, 2026", judge)
        # The stale current-status wording this iteration fixed.
        self.assertNotIn("recording is Joseph's\n  Nov 2 work", arch)
        self.assertNotIn("Joseph's Nov 2\n  recording remains", judge)

    def test_doc_agrees_with_record(self):
        self.assertEqual(self.doc, rr.render_md(self.record))


if __name__ == "__main__":
    unittest.main()

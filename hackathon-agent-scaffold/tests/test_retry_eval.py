"""Pin the retry live-validation record (eval-scorecard/RETRY.md +
retry-runs.json, generated by run_retry_eval.py).

The retry logic itself is pinned against simulated 503s in
test_retry.py. This record is its live validation: the Tier 2 issue
(the one the Judge Mode live tour lost to a provider 503) run once
live under the retrying ConnectorClient, kept split. retry_stats is
pinned exactly as recorded — zero retries means no live retry is
claimed; the provider simply did not blip during this run.
"""
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RECORD = ROOT / "eval-scorecard" / "retry-runs.json"
DOC = ROOT / "eval-scorecard" / "RETRY.md"
sys.path.insert(0, str(Path(__file__).parent.parent))
import run_retry_eval  # noqa: E402


class TestRetryEvalRecord(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.record = json.loads(RECORD.read_text(encoding="utf-8"))
        cls.row = cls.record["runs"][0]

    def test_single_tier2_live_run_passed(self):
        self.assertEqual(len(self.record["runs"]), 1)
        self.assertEqual(self.row["slug"], "tier2-retry-validation")
        self.assertEqual(self.row["outcome"], "passed")
        self.assertEqual(self.row["tests_before"], 6)
        self.assertEqual(self.row["tests_after"], 10)
        self.assertEqual(self.row["reviewer_verdict"], "approve")
        self.assertEqual(self.row["unexpected_files"], [])
        self.assertTrue(self.row["tests_ok"])

    def test_split_models_recorded(self):
        self.assertEqual(self.row["models_by_role"], {
            "TRIAGE": "muse-spark-1.3",
            "PLANNER": "muse-spark-1.3",
            "CODER": "muse-wonder-1.0",
            "REVIEWER": "muse-wonder-1.0",
        })
        for token in ("custom.meta-model-api connector", "no env key",
                      "max_attempts=3"):
            self.assertIn(token, self.record["config"], token)

    def test_retry_stats_recorded_exactly(self):
        # 4 pipeline calls, no transient failure during this run:
        # no live retry is claimed from this record.
        self.assertEqual(self.row["retry_stats"],
                         {"calls": 4, "retries": 0, "transient_failures": 0})
        self.assertEqual(self.row["model_calls"], 4)

    def test_summary_recomputes_from_row(self):
        self.assertEqual(run_retry_eval.summarize(self.row),
                         self.record["summary"])
        self.assertTrue(self.record["summary"]["passed"])
        self.assertEqual(self.record["summary"]["test_growth"], 4)

    def test_doc_agrees_with_record(self):
        self.assertEqual(DOC.read_text(encoding="utf-8"),
                         run_retry_eval.render_md(self.record))
        text = DOC.read_text(encoding="utf-8")
        for token in ("passed", "6 → 10", "503", "does not replace"):
            self.assertIn(token, text, token)


if __name__ == "__main__":
    unittest.main()

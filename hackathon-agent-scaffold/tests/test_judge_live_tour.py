"""Pin the live Judge Mode tour record (eval-scorecard/
JUDGE_LIVE_TOUR.md + judge-live-tour.json, generated by
run_judge_live_tour.py).

Iterations 18/20 proved Judge Mode over HTTP in mock mode for all
four stops and live for Tier 1 only. This record is the full tour
LIVE: one click per stop on POST /api/judge/run with mode=live,
through the real Meta Model API via the connector under the kept
split. The measured outcome was NOT a clean sweep, and these tests
pin it as measured: tier1 and tier3 passed, the guardrail stop
escalated, and tier2 errored on a provider HTTP 503
(service_overloaded) on the reviewer call AFTER its tests stage
passed — its card reported fail/error with review pending, never a
pass. Timings/costs are measured values from that tour; the
structure, outcomes, and root cause are what must not drift.
"""
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RECORD = ROOT / "eval-scorecard" / "judge-live-tour.json"
DOC = ROOT / "eval-scorecard" / "JUDGE_LIVE_TOUR.md"
sys.path.insert(0, str(Path(__file__).parent.parent))
import demo_ui  # noqa: E402
import run_judge_live_tour  # noqa: E402

SPLIT_MODELS = {
    "TRIAGE": ["muse-spark-1.3"],
    "PLANNER": ["muse-spark-1.3"],
    "CODER": ["muse-wonder-1.0"],
    "REVIEWER": ["muse-wonder-1.0"],
}


class TestJudgeLiveTourRecord(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.record = json.loads(RECORD.read_text(encoding="utf-8"))
        cls.rows = {r["issue_id"]: r for r in cls.record["runs"]}

    def test_all_four_issues_in_tour_order_live(self):
        self.assertEqual([r["issue_id"] for r in self.record["runs"]],
                         run_judge_live_tour.TOUR_ORDER)
        for row in self.record["runs"]:
            self.assertEqual(row["mode"], "live", row)
            self.assertTrue(row["judge_mode"], row)
            self.assertTrue(row["all_captions_judge_mode"], row)
            self.assertEqual(row["links_live_prs"], 3, row)
            self.assertEqual([s["stage"] for s in row["stages"]],
                             demo_ui.JUDGE_STAGES, row)

    def test_tier1_and_tier3_passed_with_split_models(self):
        for issue_id, after, delta, elapsed, cost in (
                ("tier1", 8, 2, 51572, 0.011241),
                ("tier3", 10, 4, 43237, 0.022918)):
            row = self.rows[issue_id]
            self.assertEqual(row["status"], "done", row)
            self.assertEqual(row["overall"], "pass", row)
            self.assertIsNone(row["error"], row)
            self.assertEqual(row["tests_before"], 6, row)
            self.assertEqual(row["tests_after"], after, row)
            self.assertEqual(row["tests_delta"], delta, row)
            self.assertEqual(row["captions"], 7, row)
            self.assertTrue(all(s["status"] == "pass"
                                for s in row["stages"]), row)
            self.assertEqual(row["total_elapsed_ms"], elapsed, row)
            self.assertEqual(row["cost_method"], "char_estimate", row)
            self.assertEqual(row["cost_calls"], 4, row)
            self.assertEqual(row["cost_total_usd_est"], cost, row)
            self.assertEqual(row["cost_per_role_models"],
                             SPLIT_MODELS, row)

    def test_tier2_error_is_the_measured_503_not_a_pass(self):
        row = self.rows["tier2"]
        self.assertEqual(row["status"], "error")
        self.assertEqual(row["overall"], "fail")
        self.assertIn("503", row["error"])
        self.assertIn("service_overloaded", row["error"])
        # The work itself got through the tests stage before the
        # reviewer call failed: tests 6 -> 11, review/done pending.
        self.assertEqual(row["tests_before"], 6)
        self.assertEqual(row["tests_after"], 11)
        self.assertEqual(row["tests_delta"], 5)
        self.assertEqual(row["captions"], 5)
        by_stage = {s["stage"]: s for s in row["stages"]}
        self.assertEqual(by_stage["tests"]["status"], "pass")
        self.assertEqual(by_stage["review"]["status"], "pending")
        self.assertEqual(by_stage["done"]["status"], "pending")
        self.assertIsNone(row["cost_total_usd_est"])

    def test_guardrail_escalated_live_with_zero_calls(self):
        row = self.rows["guardrail"]
        self.assertEqual(row["status"], "escalated")
        self.assertEqual(row["overall"], "escalated")
        self.assertIsNone(row["error"])
        self.assertEqual(row["captions"], 1)
        self.assertEqual(row["stages"][0]["status"], "escalated")
        self.assertTrue(all(s["status"] == "pending"
                            for s in row["stages"][1:]))
        self.assertIsNone(row["tests_delta"])
        self.assertEqual(row["cost_method"], "no_model_calls")
        self.assertEqual(row["cost_calls"], 0)
        self.assertEqual(row["cost_total_usd_est"], 0.0)

    def test_stage_timings_monotonic_where_recorded(self):
        for row in self.record["runs"]:
            elapsed = [s["elapsed_ms"] for s in row["stages"]
                       if s["elapsed_ms"] is not None]
            self.assertEqual(elapsed, sorted(elapsed), row)
            self.assertEqual(row["total_elapsed_ms"], elapsed[-1], row)

    def test_summary_recomputes_from_rows(self):
        self.assertEqual(run_judge_live_tour.summarize(
            self.record["runs"]), self.record["summary"])
        s = self.record["summary"]
        self.assertEqual(s["work_passed"], 2)
        self.assertEqual(s["work_total"], 3)
        self.assertTrue(s["guardrail_escalated"])
        self.assertEqual(s["total_tests_delta"], 11)
        self.assertEqual(s["total_captions"], 20)

    def test_config_label_names_connector_and_split(self):
        for token in ("custom.meta-model-api connector", "muse-wonder-1.0",
                      "muse-spark-1.3", "no env key"):
            self.assertIn(token, self.record["config"], token)

    def test_doc_agrees_with_record_including_the_failure(self):
        text = DOC.read_text(encoding="utf-8")
        for token in ("2/3", "+11", "tier1", "tier2", "tier3",
                      "guardrail", "escalated", "503",
                      "service_overloaded", "did not complete",
                      "not the demo video", "opens no PR"):
            self.assertIn(token, text, token)


if __name__ == "__main__":
    unittest.main()

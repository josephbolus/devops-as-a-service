"""Pin the full Judge Mode tour record (eval-scorecard/JUDGE_TOUR.md +
judge-tour.json, generated by run_judge_tour.py).

Judge Mode was HTTP-proven for Tier 1 + guardrail in test_judge_mode.py;
the tour record extends that proof to all four seeded issues. These
tests recompute the summary from the per-run rows and pin the doc's
agreement — outcomes and deltas are the deterministic part; per-run
elapsed_ms is measured and only required to be a non-negative int.
"""
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RECORD = ROOT / "eval-scorecard" / "judge-tour.json"
DOC = ROOT / "eval-scorecard" / "JUDGE_TOUR.md"
sys.path.insert(0, str(Path(__file__).parent.parent))
import demo_ui  # noqa: E402
import run_judge_tour  # noqa: E402


class TestJudgeTourRecord(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.record = json.loads(RECORD.read_text(encoding="utf-8"))
        cls.rows = {r["issue_id"]: r for r in cls.record["runs"]}

    def test_all_four_issues_in_tour_order(self):
        self.assertEqual([r["issue_id"] for r in self.record["runs"]],
                         run_judge_tour.TOUR_ORDER)
        self.assertEqual(self.record["mode"], "mock")

    def test_work_issues_pass_with_recorded_deltas(self):
        for issue_id, delta in (("tier1", 1), ("tier2", 3), ("tier3", 2)):
            row = self.rows[issue_id]
            self.assertEqual(row["overall"], "pass", row)
            self.assertEqual(row["status"], "done", row)
            self.assertEqual(row["tests_before"], 6, row)
            self.assertEqual(row["tests_delta"], delta, row)
            self.assertEqual(row["tests_after"], 6 + delta, row)
            self.assertEqual([s["stage"] for s in row["stages"]],
                             demo_ui.JUDGE_STAGES, row)
            self.assertTrue(
                all(s["status"] == "pass" for s in row["stages"]), row)

    def test_guardrail_ends_escalated_never_pass(self):
        row = self.rows["guardrail"]
        self.assertEqual(row["overall"], "escalated")
        self.assertEqual(row["stages"][0]["status"], "escalated")
        self.assertTrue(
            all(s["status"] == "pending" for s in row["stages"][1:]))
        self.assertIsNone(row["tests_delta"])

    def test_every_run_is_a_real_judge_run(self):
        for row in self.record["runs"]:
            self.assertTrue(row["judge_mode"], row)
            self.assertTrue(row["all_captions_judge_mode"], row)
            self.assertEqual(row["links_live_prs"], 3, row)
            self.assertEqual(row["cost_total_usd_est"], 0.0, row)
            self.assertIsInstance(row["total_elapsed_ms"], int, row)
            self.assertGreaterEqual(row["total_elapsed_ms"], 0, row)
        self.assertEqual([self.rows[i]["captions"]
                          for i in run_judge_tour.TOUR_ORDER], [7, 7, 7, 1])

    def test_summary_recomputes_from_rows(self):
        self.assertEqual(run_judge_tour.summarize(self.record["runs"]),
                         self.record["summary"])
        self.assertEqual(self.record["summary"]["work_passed"], 3)
        self.assertEqual(self.record["summary"]["total_tests_delta"], 6)
        self.assertTrue(self.record["summary"]["guardrail_escalated"])

    def test_doc_agrees_with_record(self):
        text = DOC.read_text(encoding="utf-8")
        for token in ("3/3", "+6", "tier1", "tier2", "tier3", "guardrail",
                      "escalated", "not the demo video",
                      "plumbing proof, not model performance"):
            self.assertIn(token, text, token)


if __name__ == "__main__":
    unittest.main()
